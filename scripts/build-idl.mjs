// Generate the canonical Anchor IDL from compiler-emitted sections; no hand-written layout.
import { spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { convertIdlToCamelCase } from '@coral-xyz/anchor/dist/cjs/idl.js';
const result = spawnSync('cargo', ['test', '--locked', '-p', 'recorda', '--features', 'idl-build', '__anchor_private_print_idl', '--', '--nocapture', '--test-threads=1'], {
  encoding: 'utf8', maxBuffer: 16 * 1024 * 1024,
  env: { ...process.env, ANCHOR_IDL_BUILD_PROGRAM_PATH: resolve('programs/recorda'), ANCHOR_IDL_BUILD_RESOLUTION: 'TRUE' }
});
if (result.status !== 0) { process.stderr.write(result.stderr); process.stderr.write(result.stdout ?? ''); process.exit(1); }
const sections = [...result.stdout.matchAll(/--- IDL begin (\w+) ---\n([\s\S]*?)\n--- IDL end \1 ---/g)];
const program = sections.find(s => s[1] === 'program');
if (!program) throw new Error('Compiler did not emit program IDL');
const idl = JSON.parse(program[2]);
idl.address = JSON.parse(sections.find(s => s[1] === 'address')?.[2] ?? '""').replace(/[^a-zA-Z0-9]/g, '');
if (!idl.address) throw new Error('Missing program address');
idl.events = []; idl.errors = []; const types = new Map(idl.types.map(t => [t.name, t]));
for (const [, kind, payload] of sections) {
  if (kind === 'event') { const e = JSON.parse(payload); idl.events.push(e.event); e.types.forEach(t => types.set(t.name, t)); }
  if (kind === 'errors') idl.errors = JSON.parse(payload);
}
idl.types = [...types.values()].sort((a,b) => a.name.localeCompare(b.name));
const json = JSON.stringify(idl, null, 2).replace(/"(?:\w+::)+(\w+)"/g, '"$1"');
const outputs = {
  'src/shared/solana/idl/recorda.json': json + '\n',
  'src/shared/solana/idl/recorda.ts': '// Generated by npm run protocol:idl. Do not edit.\nexport type Recorda = ' + JSON.stringify(convertIdlToCamelCase(JSON.parse(json)), null, 2) + ';\n'
};
if (process.argv.includes('--check')) {
  for (const [path, contents] of Object.entries(outputs)) {
    if (readFileSync(path, 'utf8') !== contents) throw new Error(`${path} differs from compiled program; run npm run protocol:idl`);
  }
  console.log('Recorda IDL and TypeScript contract match compiled program');
} else {
  mkdirSync('src/shared/solana/idl', { recursive: true });
  for (const [path, contents] of Object.entries(outputs)) writeFileSync(path, contents);
  console.log('Generated Recorda IDL and TypeScript contract');
}
